import type { IconName } from '@carrental/contracts';
import {
  Baby,
  BadgeCheck,
  Briefcase,
  CalendarCheck,
  CalendarClock,
  CarFront,
  Clock,
  Cog,
  Fuel,
  Gauge,
  Gift,
  Headset,
  LifeBuoy,
  ListChecks,
  MapPin,
  MapPinned,
  PhoneCall,
  Receipt,
  RefreshCw,
  Route,
  Search,
  ShieldCheck,
  Snowflake,
  Sparkles,
  Star,
  Users,
  Wallet,
  Zap,
  type LucideIcon,
} from 'lucide-react';

/** Allowlisted lucide icons the page builder can reference by name (keeps the site bundle lean). */
export const ICONS: Record<IconName, LucideIcon> = {
  BadgeCheck,
  Wallet,
  Clock,
  MapPinned,
  ShieldCheck,
  Receipt,
  Gauge,
  RefreshCw,
  Search,
  ListChecks,
  CarFront,
  Sparkles,
  CalendarCheck,
  CalendarClock,
  MapPin,
  Star,
  PhoneCall,
  LifeBuoy,
  Users,
  Briefcase,
  Cog,
  Zap,
  Gift,
  Fuel,
  Snowflake,
  Baby,
  Route,
  Headset,
};

export function iconFor(name: string | undefined, fallback: LucideIcon): LucideIcon {
  return (name && ICONS[name as IconName]) || fallback;
}
